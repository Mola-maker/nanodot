def contrast(first: str, second: str) -> float:
    """WCAG sRGB relative luminance contrast ratio."""

    def luminance(color: str) -> float:
        channels = [int(color[i : i + 2], 16) / 255 for i in (1, 3, 5)]
        linear = [c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4 for c in channels]
        return sum(c * w for c, w in zip(linear, (0.2126, 0.7152, 0.0722), strict=True))

    a, b = sorted((luminance(first), luminance(second)))
    return (b + 0.05) / (a + 0.05)


def material_roles(brand: BrandProfile, mode: str) -> dict[str, str]:
    """Map every supported M3 color role to brand tokens; error uses text plus icon semantics.

    No new error hue is invented. Platforms announce error text and show an icon;
    its high-contrast color pair uses the primary roles from the brand authority.
    """
    p = brand.themeColors[mode]
    inverse = brand.themeColors["dark" if mode == "light" else "light"]
    mapping = {
        "primary": "primary",
        "onPrimary": "onPrimary",
        "primaryContainer": "background",
        "onPrimaryContainer": "text",
        "secondary": "primary",
        "onSecondary": "onPrimary",
        "secondaryContainer": "background",
        "onSecondaryContainer": "text",
        "tertiary": "care",
        "onTertiary": "onPrimary",
        "tertiaryContainer": "background",
        "onTertiaryContainer": "text",
        "background": "background",
        "onBackground": "text",
        "surface": "surface",
        "onSurface": "text",
        "surfaceVariant": "background",
        "onSurfaceVariant": "text",
        "surfaceTint": "primary",
        "outline": "outline",
        "outlineVariant": "outline",
        "error": "primary",
        "onError": "onPrimary",
        "errorContainer": "background",
        "onErrorContainer": "text",
        "scrim": "text",
        "surfaceBright": "surface",
        "surfaceDim": "background",
        "surfaceContainerLowest": "background",
        "surfaceContainerLow": "surface",
        "surfaceContainer": "surface",
        "surfaceContainerHigh": "surface",
        "surfaceContainerHighest": "surface",
    }
    roles = {role: p[token] for role, token in mapping.items()}
    roles.update(
        inverseSurface=inverse["surface"],
        inverseOnSurface=inverse["text"],
        inversePrimary=inverse["primary"],
    )
    return roles


def render_dot_colors(brand: BrandProfile) -> str:
    """Also consumed by P0 rebrand so neither generator can revert the other."""
    text = (
        "package io.github.nanomuse.dot\n\n"
        "import androidx.compose.material3.darkColorScheme\n"
        "import androidx.compose.material3.lightColorScheme\n"
        "import androidx.compose.ui.graphics.Color\n\n"
        f"// {HEADER}\n// Colors: config/brand.nanodot.json.\nobject DotColors {{\n"
    )
    for mode in ("light", "dark"):
        for token, value in brand.themeColors[mode].items():
            name = token[0].upper() + token[1:]
            text += f"    val {mode.title()}{name} = Color(0xFF{value[1:]})\n"
    for mode in ("light", "dark"):
        text += f"\n    val {mode}Scheme = {mode}ColorScheme(\n"
        for role, value in material_roles(brand, mode).items():
            text += f"        {role} = Color(0xFF{value[1:]}),\n"
        text += "    )\n"
    return text + "}\n"


def load_ui(path: Path) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    if (
        not isinstance(data, dict)
        or data.get("schemaVersion") != 1
        or type(data.get("schemaVersion")) is not int
    ):
        raise ValueError("UI schemaVersion must be 1")
    if set(data) != {"schemaVersion", "space", "type", "touchTarget", "motion"}:
        raise ValueError("UI source requires schemaVersion, space, type, touchTarget and motion")
    spaces = data["space"]
    if (
        not isinstance(spaces, list)
        or not spaces
        or any(type(v) is not int or v < 0 for v in spaces)
        or spaces != sorted(set(spaces))
    ):
        raise ValueError("space must contain sorted unique non-negative integers")
    for group, keys in (("type", {"body", "care"}), ("motion", {"page", "press", "focus"})):
        values = data[group]
        if (
            not isinstance(values, dict)
            or set(values) != keys
            or any(type(v) is not int or v <= 0 for v in values.values())
        ):
            raise ValueError(f"{group} must contain positive integer values for {sorted(keys)}")
    if type(data["touchTarget"]) is not int or data["touchTarget"] < 48:
        raise ValueError("touchTarget must be an integer of at least 48")
    return data


def render_outputs(brand: BrandProfile, ui: dict) -> dict[Path, str]:
    kt = (
        "package io.github.nanomuse.dot.ui\n\n"
        "import androidx.compose.ui.unit.dp\nimport androidx.compose.ui.unit.sp\n\n"
        f"// {HEADER}\nobject DotTokens {{\n    object Space {{\n"
    )
    kt += "".join(f"        val S{v} = {v}.dp\n" for v in ui["space"])
    kt += "    }\n    object Type {\n"
    kt += "".join(f"        val {k.title()} = {v}.sp\n" for k, v in ui["type"].items())
    kt += "    }\n    object Motion {\n"
    kt += "".join(f"        const val {k.title()} = {v}\n" for k, v in ui["motion"].items())
    kt += f"    }}\n    val TouchTarget = {ui['touchTarget']}.dp\n}}\n"
    css = f"/* {HEADER} */\n:root {{\n"
    css += "".join(f"  --dot-space-{v}: {v}px;\n" for v in ui["space"])
    css += "".join(f"  --dot-type-{k}: {v / 16:g}rem;\n" for k, v in ui["type"].items())
    css += f"  --dot-touch-target: {ui['touchTarget']}px;\n"
    css += "".join(f"  --dot-motion-{k}: {v}ms;\n" for k, v in ui["motion"].items())
    css += "}\n"

    def palette_css(mode: str) -> str:
        return "".join(
            f"  --dot-{'on-primary' if k == 'onPrimary' else k}: {v};\n"
            for k, v in brand.themeColors[mode].items()
        )

    css += ':root, [data-dot-theme="light"] {\n' + palette_css("light") + "}\n"
    css += (
        '@media (prefers-color-scheme: dark) {\n  :root:not([data-dot-theme="light"]) {\n'
        + palette_css("dark")
        + "  }\n}\n"
    )
    css += '[data-dot-theme="dark"] {\n' + palette_css("dark") + "}\n"
    css += (
        "@media (prefers-reduced-motion: reduce) {\n  :root {\n"
        "    --dot-motion-page: 0ms;\n    --dot-motion-press: 0ms;\n"
        "    --dot-motion-focus: 0ms;\n  }\n}\n"
    )
    ts_data = {
        "colors": {mode: dict(p) for mode, p in brand.themeColors.items()},
        **{k: v for k, v in ui.items() if k != "schemaVersion"},
    }
    ts = f"// {HEADER}\nexport const dotTokens = " + json.dumps(ts_data, indent=2) + " as const;\n"
    swift = f"import SwiftUI\n\n// {HEADER}\nenum NanodotTokens {{\n    enum Space {{\n"
    swift += "".join(f"        static let s{v}: CGFloat = {v}\n" for v in ui["space"])
    swift += "    }\n    enum Typography {\n"
    swift += "".join(f"        static let {k}: CGFloat = {v}\n" for k, v in ui["type"].items())
    swift += "    }\n    enum Motion {\n"
    swift += "".join(
        f"        static let {k}: Double = {v / 1000:g}\n" for k, v in ui["motion"].items()
    )
    swift += f"    }}\n    static let touchTarget: CGFloat = {ui['touchTarget']}\n"
    swift += "    enum Colors {\n"
    for mode, palette in brand.themeColors.items():
        swift += f"        enum {mode.title()} {{\n"
        for key, value in palette.items():
            swift += f"            static let {key} = Color(rgb: 0x{value[1:]})\n"
        swift += "        }\n"
    swift += (
        "    }\n}\n\nprivate extension Color {\n    init(rgb: UInt32) {\n"
        "        self.init(.sRGB, red: Double((rgb >> 16) & 255) / 255,\n"
        "                  green: Double((rgb >> 8) & 255) / 255,\n"
        "                  blue: Double(rgb & 255) / 255, opacity: 1)\n"
        "    }\n}\n"
    )
    return {
        COLOR_PATH: render_dot_colors(brand),
        TOKEN_PATH: kt,
        SWIFT_PATH: swift,
        CSS_PATH: css,
        TS_PATH: ts,
        SITE_PATH: css,
    }


def generate_ui_tokens(brand_path: Path, ui_path: Path, check: bool = False) -> bool:
    """True when outputs match after generation; check never modifies the tree.

    Validate both sources and every contrast pair before creating any output.
    Stage all changed files before atomic replacement, avoiding partial writes
    on rendering/staging failure. Unchanged files retain their modification time.
    Paths resolve relative to the brand source's config parent (the repository).
    """
    brand = load_brand(brand_path)
    ui = load_ui(ui_path)
    expected = {"background", "surface", "text", "primary", "onPrimary", "care", "outline"}
    for palette in brand.themeColors.values():
        if set(palette) != expected:
            raise ValueError("UI colors require exactly the seven defined brand tokens")
    for mode in ("light", "dark"):
        roles = material_roles(brand, mode)
        for on_role in (
            "onPrimary",
            "onSecondary",
            "onTertiary",
            "onBackground",
            "onSurface",
            "onSurfaceVariant",
            "onPrimaryContainer",
            "onSecondaryContainer",
            "onTertiaryContainer",
            "onError",
            "onErrorContainer",
        ):
            role = on_role[2].lower() + on_role[3:]
            if contrast(roles[on_role], roles[role]) < 4.5:
                raise ValueError(f"{mode} {on_role}/{role} contrast must be at least 4.5")
    root = brand_path.resolve().parent.parent
    outputs = render_outputs(brand, ui)
    changed = {
        root / path: text
        for path, text in outputs.items()
        if not (root / path).exists() or (root / path).read_text(encoding="utf-8") != text
    }
    if check:
        return not changed
    staged = []
    try:
        for path, text in changed.items():
            path.parent.mkdir(parents=True, exist_ok=True)
            with tempfile.NamedTemporaryFile(
                mode="w", encoding="utf-8", dir=path.parent, prefix=".dot-tokens-", delete=False
            ) as file:
                staged.append((Path(file.name), path))
                file.write(text)
        for temporary, path in staged:
            os.replace(temporary, path)
    finally:
        for temporary, _ in staged:
            temporary.unlink(missing_ok=True)
    return True
